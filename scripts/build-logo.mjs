// Outlines the Arai logo (அறை and the square mark அ) from the Kavivanar
// typeface (SIL Open Font License 1.1) into fixed SVG paths, so the logo never
// depends on a web font loading. Tamil shaping (vowel-sign reordering) is done
// by HarfBuzz, exactly as a browser would.
//
//   npm run build:logo
//
// Writes apps/web/src/components/logoPaths.ts and apps/web/public/favicon.svg.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { inflateSync } from 'node:zlib';
import * as hb from 'harfbuzzjs';

const require = createRequire(import.meta.url);
const woffPath = require.resolve('@fontsource/kavivanar/files/kavivanar-tamil-400-normal.woff');

/** WOFF 1.0 → plain SFNT (TrueType) so HarfBuzz can read it. */
function woffToSfnt(buf) {
  const dv = new DataView(buf.buffer, buf.byteOffset, buf.byteLength);
  if (dv.getUint32(0) !== 0x774f4646) throw new Error('not a WOFF file');
  const flavor = dv.getUint32(4);
  const numTables = dv.getUint16(12);
  const tables = [];
  for (let i = 0; i < numTables; i++) {
    const o = 44 + i * 20;
    tables.push({
      tag: dv.getUint32(o),
      offset: dv.getUint32(o + 4),
      compLength: dv.getUint32(o + 8),
      origLength: dv.getUint32(o + 12),
      checksum: dv.getUint32(o + 16),
    });
  }
  const headerLen = 12 + numTables * 16;
  let total = headerLen;
  for (const t of tables) total += (t.origLength + 3) & ~3;
  const out = new Uint8Array(total);
  const ov = new DataView(out.buffer);
  let es = 0;
  while (1 << (es + 1) <= numTables) es++;
  ov.setUint32(0, flavor);
  ov.setUint16(4, numTables);
  ov.setUint16(6, (1 << es) * 16);
  ov.setUint16(8, es);
  ov.setUint16(10, numTables * 16 - (1 << es) * 16);
  let offset = headerLen;
  tables.forEach((t, i) => {
    const raw = buf.subarray(t.offset, t.offset + t.compLength);
    const data = t.compLength < t.origLength ? inflateSync(raw) : raw;
    out.set(data, offset);
    const r = 12 + i * 16;
    ov.setUint32(r, t.tag);
    ov.setUint32(r + 4, t.checksum);
    ov.setUint32(r + 8, offset);
    ov.setUint32(r + 12, t.origLength);
    offset += (t.origLength + 3) & ~3;
  });
  return out;
}

const sfnt = woffToSfnt(readFileSync(woffPath));
const blob = new hb.Blob(sfnt.buffer);
const face = new hb.Face(blob);
const font = new hb.Font(face);

/** Shape text and return one SVG path (font units, y down) plus its bounds. */
function outline(text) {
  const buffer = new hb.Buffer();
  buffer.addText(text);
  buffer.guessSegmentProperties();
  hb.shape(font, buffer);
  const infos = buffer.getGlyphInfos();
  const positions = buffer.getGlyphPositions();
  let x = 0;
  let d = '';
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  infos.forEach((g, i) => {
    const p = positions[i];
    const gx = x + p.xOffset;
    const gy = p.yOffset;
    const path = font.glyphToPath(g.codepoint);
    // Transform every coordinate pair: flip y (fonts are y-up), offset by pen position.
    d += path.replace(/([MLQCZ])([^MLQCZ]*)/g, (_m, cmd, args) => {
      const nums = args.trim() ? args.trim().split(/[\s,]+/).map(Number) : [];
      const pts = [];
      for (let k = 0; k < nums.length; k += 2) {
        const px = nums[k] + gx;
        const py = -(nums[k + 1] + gy);
        minX = Math.min(minX, px); maxX = Math.max(maxX, px);
        minY = Math.min(minY, py); maxY = Math.max(maxY, py);
        pts.push(`${Math.round(px)} ${Math.round(py)}`);
      }
      return cmd + pts.join(' ');
    });
    x += p.xAdvance;
  });
  buffer.destroy?.();
  return { d, box: { minX, minY, maxX, maxY } };
}

/** Pad the box, and report a viewBox with room for the -3° hand tilt. */
function viewBox({ minX, minY, maxX, maxY }, pad) {
  const w = maxX - minX;
  const h = maxY - minY;
  return [Math.round(minX - pad * w), Math.round(minY - pad * h), Math.round(w * (1 + 2 * pad)), Math.round(h * (1 + 2 * pad))];
}

const word = outline('அறை');
const mark = outline('அ');
const wordVB = viewBox(word.box, 0.06);
const markVB = viewBox(mark.box, 0.08);
const cx = (b) => Math.round((b.minX + b.maxX) / 2);
const cy = (b) => Math.round((b.minY + b.maxY) / 2);

writeFileSync(
  new URL('../apps/web/src/components/logoPaths.ts', import.meta.url),
  `// Generated by scripts/build-logo.mjs from Kavivanar (SIL OFL 1.1). Do not edit.
export const WORDMARK = {
  viewBox: '${wordVB.join(' ')}',
  d: '${word.d}',
  tilt: 'rotate(-3 ${cx(word.box)} ${cy(word.box)})',
} as const;

export const MARK = {
  viewBox: '${markVB.join(' ')}',
  d: '${mark.d}',
  tilt: 'rotate(-3 ${cx(mark.box)} ${cy(mark.box)})',
} as const;
`,
);

// Favicon / app icon: the square mark on the void, centred.
const side = Math.max(mark.box.maxX - mark.box.minX, mark.box.maxY - mark.box.minY) * 1.18;
const ox = cx(mark.box) - side / 2;
const oy = cy(mark.box) - side / 2;
writeFileSync(
  new URL('../apps/web/public/favicon.svg', import.meta.url),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${Math.round(ox)} ${Math.round(oy)} ${Math.round(side)} ${Math.round(side)}"><rect x="${Math.round(ox)}" y="${Math.round(oy)}" width="${Math.round(side)}" height="${Math.round(side)}" rx="${Math.round(side * 0.22)}" fill="#08080A"/><path fill="#F2EFEA" transform="rotate(-3 ${cx(mark.box)} ${cy(mark.box)})" d="${mark.d}"/></svg>\n`,
);
console.log('logo written', { wordVB, markVB });
